def describe(episodes: list[dict]) -> dict:
    kinds = defaultdict(int)
    outcomes = defaultdict(int)
    changed = 0
    total = 0
    statuses = defaultdict(int)
    disp = defaultdict(int)
    for ep in episodes:
        for s in ep["steps"]:
            if s["setup"]:
                continue
            total += 1
            kinds[s["type"]] += 1
            outcomes[s["ledger_outcome"]] += 1
            changed += bool(s["truth"]["changed_actions"])
            for v in s["truth"]["pred"].values():
                statuses[PRED_STATUS_NAMES[v]] += 1
            for a in s["truth"]["actions"].values():
                disp[a["disposition"]] += 1
    return {
        "episodes": len(episodes), "events": total, "event_types": dict(kinds), "ledger_outcomes": dict(outcomes),
        "events_changing_some_action": changed, "predicate_status": dict(statuses), "action_disposition": dict(disp),
        "mean_predicates": sum(len(e["schema"]["predicates"]) for e in episodes) / max(1, len(episodes)),
        "mean_records": sum(len(e["links"]) for e in episodes) / max(1, len(episodes)),
    }
